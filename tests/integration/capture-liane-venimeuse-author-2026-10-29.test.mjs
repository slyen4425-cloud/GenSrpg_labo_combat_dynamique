import test from "node:test";
import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {createHash} from "node:crypto";
import {CAPTURE_SHOWCASE_SKILL_PRESET_FILES_V1} from "../../src/catalogs/capture-showcase-skill-presets-v1.js";
import {importCaptureTransferJsonV1} from "../../src/adapters/input/capture/capture-entity-transfer-v1.js";
const source="data/capture/source-exports/gensrpg-capture-skill-liane_venimeuse-2026-10-29.json";
const active="data/capture/showcase/liane_venimeuse.capture-skill-transfer-v1.json";
const read=p=>readFile(new URL("../../"+p,import.meta.url),"utf8");
const sha=s=>createHash("sha256").update(s).digest("hex");

test("RED: exact author Liane venimeuse export is the single active Capture skill preset",async()=>{
 const original=await read(source);
 assert.equal(Buffer.byteLength(original),2937);
 assert.equal(sha(original),"15c7e1ad305b3ede49698e835675d1b95fdb68ac267cf8778435ded388264a7d");
 assert.equal(await read(active),original,"active author preset must equal exact source bytes");
 assert.equal(CAPTURE_SHOWCASE_SKILL_PRESET_FILES_V1.filter(path=>path===active).length,1);
 assert.equal(new Set(CAPTURE_SHOWCASE_SKILL_PRESET_FILES_V1).size,CAPTURE_SHOWCASE_SKILL_PRESET_FILES_V1.length);
 const transfer=importCaptureTransferJsonV1(original);
 assert.equal(transfer.kind,"skill");
 const draft=transfer.value.draft;
 assert.equal(draft.id,"liane_venimeuse");
 assert.equal(draft.definition.id,"liane_venimeuse");
 assert.equal(draft.definition.name,"Liane venimeuse");
 assert.equal(draft.requiredLevel,20);
 assert.deepEqual(draft.usageScopes,["capture","combat"]);
 assert.equal(draft.definition.loadoutSlot,"ultimate");
 assert.equal(draft.definition.form,"contact");
 assert.equal(draft.definition.element,"nature");
 assert.equal(draft.definition.energyCost,6);
 assert.equal(draft.definition.preparationMs,2200);
 assert.equal(draft.definition.travelMs,800);
 assert.equal(draft.definition.maxUsesPerCombat,1);
 assert.deepEqual(draft.definition.targetRelations,["enemy"]);
 assert.deepEqual(draft.definition.targetLocations,["reserve"]);
 assert.deepEqual(draft.definition.effects.map(f=>f.kind),["force_reserve_switch","apply_marker","apply_marker"]);
 assert.deepEqual(draft.definition.effects[0],{kind:"force_reserve_switch",targetScope:"target"});
 const [sangsue,poison]=draft.definition.effects.slice(1);
 assert.deepEqual([sangsue.charges,sangsue.marker.id,sangsue.marker.periodic.kind,sangsue.marker.periodic.amount,sangsue.marker.periodic.intervalMs],[2,"graine-sansue","life_steal",5,3000]);
 assert.deepEqual([poison.charges,poison.marker.id,poison.marker.periodic.kind,poison.marker.periodic.amount,poison.marker.periodic.intervalMs],[2,"poison","damage",5,5000]);
 assert.equal(draft.presentation,null,"source export is authoritative: do not invent beam visual binding");
});
