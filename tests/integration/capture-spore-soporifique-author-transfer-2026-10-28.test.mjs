import test from "node:test";
import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {createHash} from "node:crypto";
import {CAPTURE_SHOWCASE_SKILL_PRESET_FILES_V1} from "../../src/catalogs/capture-showcase-skill-presets-v1.js";
import {importCaptureTransferJsonV1} from "../../src/adapters/input/capture/capture-entity-transfer-v1.js";
const read = (p)=>readFile(new URL("../../"+p, import.meta.url),"utf8");
const canonical="data/capture/showcase/Spore_soporifique.capture-skill-transfer-v1.json";
const archive="data/capture/source-exports/gensrpg-capture-skill-Spore_soporifique-2026-10-28.json";
test("Spore soporifique: immutable author skill and single canonical skill registration",async()=>{
 const raw=await read(archive);
 assert.equal(createHash("sha256").update(raw).digest("hex"),"b1ac566d24a3aaff996661a7127c2e95f9dd3011b5e09436df1050a3d681fbf2");
 assert.equal(await read(canonical),raw);
 assert.equal(CAPTURE_SHOWCASE_SKILL_PRESET_FILES_V1.filter(p=>p===canonical).length,1);
 assert.equal(new Set(CAPTURE_SHOWCASE_SKILL_PRESET_FILES_V1).size,CAPTURE_SHOWCASE_SKILL_PRESET_FILES_V1.length);
 const transfer=importCaptureTransferJsonV1(raw);
 assert.equal(transfer.kind,"skill");
 const d=transfer.value.draft;
 assert.equal(d.id,"Spore_soporifique");
 assert.equal(d.requiredLevel,10);
 assert.deepEqual(d.usageScopes,["capture","combat"]);
 assert.equal(d.definition.name,"Spore soporifique");
 assert.equal(d.definition.category,"buff_debuff");
 assert.equal(d.definition.form,"projectile");
 assert.equal(d.definition.projectileTargeting,"expanding_wave");
 assert.deepEqual(d.definition.expandingWave,{startRadiusPct:3,endRadiusPct:65,thicknessPct:6});
 assert.equal(d.definition.element,"nature");
 assert.equal(d.definition.energyCost,3);
 assert.equal(d.definition.preparationMs,500);
 assert.equal(d.definition.travelMs,500);
 assert.equal(d.definition.cooldownMs,30000);
 assert.equal(d.definition.effects.length,1);
 assert.equal(d.definition.effects[0].kind,"apply_status");
 assert.equal(d.definition.effects[0].status.kind,"stun");
 assert.equal(d.definition.effects[0].status.durationMs,10000);
 assert.equal(d.presentation.visual.travel.assetId,"pack:capture:sprite-fire-bubble-expansion-01");
 assert.equal(d.presentation.statusVisuals["status-1"].sprite.assetId,"pack:capture:sprite-sommeil-z-status-01");
});
