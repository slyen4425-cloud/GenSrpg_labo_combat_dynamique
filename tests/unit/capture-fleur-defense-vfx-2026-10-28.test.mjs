import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync, existsSync} from "node:fs";
import {resolve} from "node:path";
import {createHash} from "node:crypto";
import {fileURLToPath} from "node:url";
import {dirname} from "node:path";
const root=resolve(dirname(fileURLToPath(import.meta.url)),"../..");
const folder=resolve(root,"assets/library/capture/sprites/skills/fleur_defense");
const id="pack:capture:sprite-fleur-defense-01";
const sha256=b=>createHash("sha256").update(b).digest("hex");
const json=p=>JSON.parse(readFileSync(p,"utf8"));
test("Fleur défense: 12 real RGBA PNG frames, atlas and last held pose in sole catalog",()=>{
 const catalog=json(resolve(root,"data/assets/catalog/global-visual-assets.v1.json"));
 assert.equal(catalog.counts.assets,catalog.assets.length);
 assert.equal(catalog.counts.sprites,catalog.assets.filter(a=>a.assetType==="sprite").length);
 assert.equal(new Set(catalog.assets.map(a=>a.id)).size,catalog.assets.length);
 const assets=catalog.assets.filter(a=>a.id===id);
 assert.equal(assets.length,1);
 const asset=assets[0];
 assert.equal(asset.category,"skill");
 assert.equal(asset.resource.frameCount,12);
 assert.equal(asset.resource.playbackMode,"once");
 assert.equal(asset.resource.holdLastFrame,true);
 assert.ok(asset.compatibility.uses.includes("editor"));
 const seq=json(resolve(folder,"sprite_skill_fleur_defense_sequence_01.json"));
 const prov=json(resolve(folder,"provenance.json"));
 assert.equal(prov.originalGitBlobSha,"5f3bb2b288f8fdc4dc9c22bb474dfce13bb9b3c4");
 assert.equal(seq.id,id);
 assert.equal(seq.frame_count,12);
 assert.equal(seq.holdLastFrame,true);
 assert.equal(seq.holdFrameIndex,11);
 assert.equal(seq.frames.length,12);
 const seen=new Set();
 for(let i=0;i<12;i++){
   const rel="frames/fleur_defense_"+String(i).padStart(2,"0")+".png";
   assert.equal(seq.frames[i],rel);
   const buf=readFileSync(resolve(folder,rel));
   assert.equal(buf.toString("hex",0,8),"89504e470d0a1a0a");
   assert.equal(buf.readUInt32BE(16),512);
   assert.equal(buf.readUInt32BE(20),512);
   assert.equal(sha256(buf),prov.originalFileSha256[rel]);
   seen.add(sha256(buf));
 }
 assert.equal(seen.size,12);
 const atlas=readFileSync(resolve(root,catalog.storage.libraryRoot,asset.resource.file));
 assert.equal(atlas.toString("ascii",0,4),"RIFF");
 assert.equal(atlas.toString("ascii",8,12),"WEBP");
 assert.equal(sha256(atlas),prov.generatedAtlasSha256);
 assert.ok(existsSync(resolve(folder,seq.preview)));
});
