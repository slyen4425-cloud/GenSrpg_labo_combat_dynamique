import test from "node:test";
import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {createHash} from "node:crypto";
import {importCaptureTransferJsonV1,planCaptureTransferImportV1} from "../../src/adapters/input/capture/capture-entity-transfer-v1.js";
import {buildCaptureEditorDatabaseV1,applyCaptureTransferPlanToEditorStateV1} from "../../src/ui/capture-editor-file-transfer-v1.js";
import {normalizeCaptureStatRegistryV1} from "../../src/contracts/capture-stat-registry-v1.js";
import {normalizeCaptureProgressionRulesV1} from "../../src/contracts/capture-progression-rules-v1.js";
import {CAPTURE_SHOWCASE_SKILL_PRESET_FILES_V1} from "../../src/catalogs/capture-showcase-skill-presets-v1.js";
const active="data/capture/showcase/tempete_rouille.capture-skill-transfer-v1.json";
const archive="data/capture/source-exports/gensrpg-capture-skill-tempete_rouille-2026-10-20.json";
const text=p=>readFile(new URL("../../"+p,import.meta.url),"utf8");
const hash=v=>createHash("sha256").update(v).digest("hex");
test("author Tempête de rouille stays byte-exact, French channel included, loaded once",async()=>{
 const [a,b,newSource]=await Promise.all([text(active),text(archive),text("data/capture/source-exports/gensrpg-capture-skill-tempete_rouille-2026-10-21.json")]);
 assert.equal(hash(b),"e154956cbb52c957da5487ee8704d8a13112ed9787e172a9454316a5e5e7e8cf", "preserve October 20 historical source");
 assert.equal(hash(a),"d26de89a321526f9c69b64e9e9383e524f1396e20ed7574ab67013616f1a3bc8", "new October 21 source");
 assert.equal(a,newSource);
 assert.notEqual(a,b, "historical revision must remain archived, not active");
 assert.equal(CAPTURE_SHOWCASE_SKILL_PRESET_FILES_V1.filter(p=>p===active).length,1);
 assert.equal(CAPTURE_SHOWCASE_SKILL_PRESET_FILES_V1.filter(p=>p===archive).length,0);
 const d=importCaptureTransferJsonV1(a).value.draft;
 assert.equal(d.id,"tempete_rouille");
 assert.equal(d.definition.id,d.id);
 assert.equal(d.presentation.subjectId,d.id);
 assert.equal(d.requiredLevel,20);
 assert.equal(d.definition.loadoutSlot,"ultimate");
 assert.equal(d.definition.category,"counter");
 assert.equal(d.definition.element,"steel");
 assert.equal(d.definition.energyCost,6);
 assert.equal(d.definition.preparationMs,700);
 assert.equal(d.definition.cooldownMs,40000);
 assert.equal(d.definition.effects[0].kind,"persistent_zone");
 assert.equal(d.definition.effects[0].tickEffect.channel,"acier");
 assert.equal(d.definition.effects[0].tickEffect.amount,20);
 assert.equal(d.definition.effects[0].tickIntervalMs,1000);
 assert.equal(d.definition.effects[0].durationMs,15000);
 assert.equal(d.presentation.visual.aura.assetId,"pack:capture:sprite-rust-whirlwind-cast-01");
 assert.equal(d.presentation.visual.icon.assetId,"pack:capture:icon-skill-tourbillons-rouille-01");
});
test("single configuredSkills owner round trips without duplication",async()=>{
 const transfer=importCaptureTransferJsonV1(await text(active));
 const statRegistry=normalizeCaptureStatRegistryV1(JSON.parse(await text("data/capture/monster-capture-stat-registry.v1.json")));
 const progressionRules=normalizeCaptureProgressionRulesV1(JSON.parse(await text("data/capture/monster-capture-progression-rules.v1.json")));
 const configuredSkills=new Map(),configuredCreatures=new Map();
 const deps={statRegistry,progressionRules,configuredSkills,configuredCreatures};
 const plan=planCaptureTransferImportV1({currentDatabase:buildCaptureEditorDatabaseV1(deps),transfer,mode:"replace"});
 assert.equal(plan.action,"insert-skill");
 applyCaptureTransferPlanToEditorStateV1({plan,...deps});
 assert.equal(configuredSkills.size,1);
 assert.deepEqual(configuredSkills.get("tempete_rouille"),transfer.value.draft);
 const again=planCaptureTransferImportV1({currentDatabase:buildCaptureEditorDatabaseV1(deps),transfer,mode:"replace"});
 assert.equal(again.action,"noop");
});
