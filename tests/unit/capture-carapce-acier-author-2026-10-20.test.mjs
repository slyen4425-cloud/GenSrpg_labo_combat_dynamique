import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { importCaptureTransferJsonV1, planCaptureTransferImportV1 } from "../../src/adapters/input/capture/capture-entity-transfer-v1.js";
import { applyCaptureTransferPlanToEditorStateV1, buildCaptureEditorDatabaseV1 } from "../../src/ui/capture-editor-file-transfer-v1.js";
import { humanConfiguredSkillLibraryEntriesV1, humanSkillEditorFieldsFromDraftV1, buildHumanSkillDraftV1 } from "../../src/ui/capture-editor-human-v2.js";
import { normalizeCaptureStatRegistryV1 } from "../../src/contracts/capture-stat-registry-v1.js";
import { normalizeCaptureProgressionRulesV1 } from "../../src/contracts/capture-progression-rules-v1.js";
import { CAPTURE_SHOWCASE_SKILL_PRESET_FILES_V1 } from "../../src/catalogs/capture-showcase-skill-presets-v1.js";

const path = "data/capture/showcase/carapce_acier.capture-skill-transfer-v1.json";
const text = p => readFile(new URL("../../" + p, import.meta.url), "utf8");
test("author Carapace d'acier is loaded exactly once with its non-corrected data", async () => {
 assert.equal(CAPTURE_SHOWCASE_SKILL_PRESET_FILES_V1.filter(p=>p===path).length,1);
 const transfer=importCaptureTransferJsonV1(await text(path));
 assert.equal(transfer.kind,"skill");
 const d=transfer.value.draft;
 assert.equal(d.id,"carapce_acier");
 assert.equal(d.definition.id,d.id);
 assert.equal(d.definition.name,"Carapace d acier");
 assert.equal(d.description,"Protège la créature");
 assert.equal(d.requiredLevel,5);
 assert.deepEqual(d.usageScopes,["capture","combat"]);
 assert.equal(d.definition.category,"buff_debuff");
 assert.equal(d.definition.form,"contact");
 assert.equal(d.definition.element,"steel");
 assert.equal(d.definition.energyCost,4);
 assert.equal(d.definition.preparationMs,2500);
 assert.equal(d.definition.cooldownMs,30000);
 assert.deepEqual(d.definition.targetRelations,["self"]);
 assert.deepEqual(d.definition.targetLocations,["active"]);
 assert.equal(d.definition.effects.length,1);
 const effect=d.definition.effects[0];
 assert.equal(effect.kind,"apply_status");
 assert.equal(effect.targetScope,"self");
 assert.equal(effect.status.id,"status-1");
 assert.equal(effect.status.statId,"defense");
 assert.equal(effect.status.modifierMode,"points");
 assert.equal(effect.status.deltaPoints,500);
 assert.equal(effect.status.durationMs,15000);
 assert.equal(effect.status.stacking,"refresh");
 assert.equal(d.presentation.version,3);
 assert.equal(d.presentation.visual.icon.assetId,"pack:capture:icon-skill-armure-de-pointe-01");
 assert.equal(d.presentation.statusVisuals["status-1"].sprite.assetId,"pack:capture:sprite-steel-carapace-hold-01");
 assert.equal(d.presentation.statusVisuals["status-1"].sprite.playbackMode,"hold-last");
 assert.deepEqual(d.presentation.audio,{});
});
test("skill follows the existing configuredSkills owner and round trips through active editor",async()=>{
 const input=importCaptureTransferJsonV1(await text(path));
 const registry=normalizeCaptureStatRegistryV1(JSON.parse(await text("data/capture/monster-capture-stat-registry.v1.json")));
 const progressionRules=normalizeCaptureProgressionRulesV1(JSON.parse(await text("data/capture/monster-capture-progression-rules.v1.json")));
 const configuredSkills=new Map();
 const configuredCreatures=new Map();
 const currentDatabase=buildCaptureEditorDatabaseV1({statRegistry:registry,progressionRules,configuredSkills,configuredCreatures});
 const plan=planCaptureTransferImportV1({currentDatabase,transfer:input,mode:"replace"});
 assert.equal(plan.action,"insert-skill");
 applyCaptureTransferPlanToEditorStateV1({plan,configuredSkills,configuredCreatures,statRegistry:registry,progressionRules});
 assert.equal(configuredSkills.size,1);
 const entries=humanConfiguredSkillLibraryEntriesV1(configuredSkills);
 assert.equal(entries.length,1);
 assert.equal(entries[0].id,"carapce_acier");
 const active=configuredSkills.get("carapce_acier");
 assert.deepEqual(active,input.value.draft);
 assert.deepEqual(buildHumanSkillDraftV1(humanSkillEditorFieldsFromDraftV1(active)),active);
 const again=planCaptureTransferImportV1({currentDatabase:buildCaptureEditorDatabaseV1({statRegistry:registry,progressionRules,configuredSkills,configuredCreatures}),transfer:input,mode:"replace"});
 assert.equal(again.action,"replace-skill");
 applyCaptureTransferPlanToEditorStateV1({plan:again,configuredSkills,configuredCreatures,statRegistry:registry,progressionRules});
 assert.equal(configuredSkills.size,1);
});
