import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
const root = process.cwd();
const id = "pack:capture:icon-skill-tailwind-feather-01";
const media = "capture/icons/skills/icon_skill_tailwind_feather_01.webp";
const catalog = JSON.parse(fs.readFileSync(path.join(root,"data/assets/catalog/global-visual-assets.v1.json"),"utf8"));
const provenance = JSON.parse(fs.readFileSync(path.join(root,"assets/library/capture/icons/skills/tailwind_feather_v1.provenance.json"),"utf8"));
test("Vent arrière uses the single canonical catalog and preserves earlier assets", () => {
  assert.equal(catalog.storage.branch, "global-assets");
  assert.equal(catalog.counts.assets, catalog.assets.length);
  assert.equal(catalog.counts.icons, catalog.assets.filter(x=>x.assetType==="icon").length);
  assert.ok(catalog.counts.assets>=135);
  assert.ok(catalog.counts.icons>=46);
  assert.equal(new Set(catalog.assets.map(x=>x.id)).size,catalog.assets.length);
  const matches=catalog.assets.filter(x=>x.id===id);
  assert.equal(matches.length,1);
  const a=matches[0];
  assert.equal(a.label,"Vent arrière");
  assert.equal(a.assetType,"icon");
  assert.equal(a.category,"skill");
  assert.equal(a.resource.file,media);
  assert.equal(a.resource.mime,"image/webp");
  assert.ok(a.tags.includes("air"));
  assert.deepEqual(a.compatibility.uses,["combat","capture","editor"]);
  for(const historic of ["pack:capture:icon-skill-seismic-shock-01","pack:capture:icon-skill-healing-wave-01","pack:capture:icon-skill-flame-storm-01","pack:capture:sprite-air-wind-tornado-01"])assert.equal(catalog.assets.filter(x=>x.id===historic).length,1,historic);
});
test("Vent arrière is the actual verified 128px illustrated WebP (not an empty placeholder)", () => {
  const p=path.join(root,"assets/library",media);
  const bytes=fs.readFileSync(p);
  assert.equal(bytes.length,5206);
  assert.equal(bytes.toString("ascii",0,4),"RIFF");
  assert.equal(bytes.readUInt32LE(4)+8,bytes.length);
  assert.equal(bytes.toString("ascii",8,12),"WEBP");
  assert.equal(bytes.toString("ascii",12,16),"VP8 ");
  assert.equal(bytes.toString("hex",23,26),"9d012a");
  assert.equal(bytes.readUInt16LE(26)&0x3fff,128);
  assert.equal(bytes.readUInt16LE(28)&0x3fff,128);
  const hash=createHash("sha256").update(bytes).digest("hex");
  assert.equal(hash,provenance.derivedSha256);
  assert.equal(hash,"85b57236179f89b6313e063f74e41199947dd3485d017901edeee9c359d385f8");
  assert.equal(provenance.assetId,id);
  assert.equal(provenance.derivedFile,media);
  assert.equal(provenance.sourceSha256,"cc75b288a3be3e04589c19ba28c875ee038b15fd8c004e41c89a93d8ad1bbda5");
});
