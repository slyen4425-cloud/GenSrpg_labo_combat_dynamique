import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {createHash} from "node:crypto";
import {dirname, resolve} from "node:path";
import {fileURLToPath} from "node:url";
const root=resolve(dirname(fileURLToPath(import.meta.url)),"../..");
const read=path=>readFileSync(resolve(root,path));
const catalog=JSON.parse(read("data/assets/catalog/global-visual-assets.v1.json"));
const provenance=JSON.parse(read("assets/library/capture/icons/skills/capture_graine_sangsue_2026_10_28.provenance.json"));
const sha256=b=>createHash("sha256").update(b).digest("hex");
const gitsha=b=>createHash("sha1").update(Buffer.from("blob "+b.length+String.fromCharCode(0))).update(b).digest("hex");
test("Graine sangsue real WebP 128 px, canonical editor catalog and unchanged Sangsue icon",()=>{
 assert.equal(provenance.assetId,"pack:capture:icon-skill-graine-sangsue-01");
 assert.equal(catalog.counts.assets,catalog.assets.length);
 assert.equal(catalog.counts.icons,catalog.assets.filter(a=>a.assetType==="icon").length);
 assert.equal(new Set(catalog.assets.map(a=>a.id)).size,catalog.assets.length);
 const entries=catalog.assets.filter(a=>a.id===provenance.assetId);
 assert.equal(entries.length,1);
 const item=entries[0];
 assert.equal(item.label,"Graine sangsue");
 assert.equal(item.category,"skill");
 assert.equal(item.assetType,"icon");
 assert.equal(item.resource.mime,"image/webp");
 assert.ok(item.compatibility.uses.includes("editor"));
 assert.equal(item.resource.file,provenance.derivedFile);
 const existing=catalog.assets.filter(a=>a.id==="pack:capture:icon-skill-sangsue-01");
 assert.equal(existing.length,1);
 assert.equal(existing[0].resource.file,"capture/icons/skills/icon_skill_sangsue_01.webp");
 const b=read(catalog.storage.libraryRoot+provenance.derivedFile);
 assert.equal(b.length,provenance.bytes);
 assert.equal(sha256(b),provenance.derivedSha256);
 assert.equal(gitsha(b),provenance.gitBlobSHA);
 assert.equal(b.toString("ascii",0,4),"RIFF");
 assert.equal(b.toString("ascii",8,12),"WEBP");
 assert.equal(b.toString("ascii",12,16),"VP8 ");
 assert.equal(b.readUInt16LE(26)&0x3fff,128);
 assert.equal(b.readUInt16LE(28)&0x3fff,128);
});
