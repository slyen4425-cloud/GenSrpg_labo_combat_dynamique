import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { createHash } from "node:crypto";

const root = process.cwd();
const id = "pack:capture:sprite-armure-ronces-plante-carnivore-back-01";
const faceId = "pack:capture:sprite-armure-ronces-plante-carnivore-01";
const base = "assets/library/capture/sprites/skills/armure_ronces_plante_carnivore/back";
const read = (p) => readFileSync(join(root, p));
const sha = (b) => createHash("sha256").update(b).digest("hex");

test("armure de ronces dos: one true six-frame transparent mask with held finish, without replacing face", () => {
  const cat = JSON.parse(read("data/assets/catalog/global-visual-assets.v1.json"));
  assert.equal(cat.counts.assets, cat.assets.length);
  assert.equal(cat.counts.sprites, cat.assets.filter(a=>a.assetType==="sprite").length);
  assert.equal(new Set(cat.assets.map(a=>a.id)).size, cat.assets.length);
  assert.equal(cat.assets.filter(a=>a.id === faceId).length,1,"approved face overlay must remain");
  const match = cat.assets.filter(a=>a.id === id);
  assert.equal(match.length,1,"back overlay must have exactly one catalog entry");
  const asset = match[0];
  assert.equal(asset.category,"skill");
  assert.ok(asset.tags.includes("nature") && asset.tags.includes("overlay") && asset.tags.includes("player") && asset.tags.includes("back"));
  assert.equal(asset.resource.frameCount,6);
  assert.equal(asset.resource.format,"sprite-strip");
  assert.equal(asset.resource.playbackMode,"once");
  assert.equal(asset.resource.holdLastFrame,true);
  assert.equal(asset.resource.persistentFrameIndex,5);
  const manifest = JSON.parse(read(base+"/sequence.manifest.json"));
  assert.equal(manifest.assetId,id);
  assert.equal(manifest.referenceView,"player_back");
  assert.equal(manifest.frameCount,6);
  assert.deepEqual(manifest.frameSize,[512,512]);
  assert.equal(manifest.playbackMode,"once");
  assert.equal(manifest.holdLastFrame,true);
  assert.equal(manifest.holdFrameIndex,5);
  assert.equal(manifest.sourceArchiveSha256,"d3cdba93cc9102b760a7fd0e0dc49e0b0f0ad9d6d524a10f6940388f7688a276");
  assert.equal(manifest.sourceGitBlobSha,"0587d83efb6a1a1f18f822e406065afec552a2d5");
  assert.equal(manifest.frames.length,6);
  assert.equal(manifest.frameDurationsMs.length,6);
  assert.equal(manifest.runtimeMaskOnly,true);
  const unique = new Set();
  for(let i=0;i<6;i++){
    const frame = manifest.frames[i];
    assert.equal(frame.index,i);
    assert.equal(frame.file,"frames/armure_ronces_dos_"+String(i+1).padStart(2,"0")+".png");
    const bytes=read(base+"/"+frame.file);
    assert.equal(bytes.subarray(0,8).toString("hex"),"89504e470d0a1a0a");
    assert.equal(bytes.readUInt32BE(16),512);
    assert.equal(bytes.readUInt32BE(20),512);
    assert.equal(bytes[25],6,"PNG RGBA");
    assert.equal(sha(bytes),frame.sha256);
    assert.ok(Math.min(...frame.marginsLTRB)>=30);
    unique.add(frame.sha256);
  }
  assert.equal(unique.size,6);
  const atlas=read(base+"/"+manifest.atlas.file);
  assert.equal(atlas.toString("ascii",0,4),"RIFF");
  assert.equal(atlas.toString("ascii",8,12),"WEBP");
  assert.equal(sha(atlas),manifest.atlas.sha256);
  assert.equal(manifest.atlas.width,3072);
  assert.equal(manifest.atlas.height,512);
  assert.equal(asset.resource.file,base.slice("assets/library/".length)+"/"+manifest.atlas.file);
  const preview=read(base+"/"+manifest.preview.mask);
  assert.ok(preview.length>10000);
  assert.ok(!asset.resource.file.includes("sur_creature"));
  assert.ok(existsSync(join(root,base,"sources/revue_sur_creature.webp")));
});